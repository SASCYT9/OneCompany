function cleanCaption(value) {
  return value
    .replace(/^\d+ likes, \d+ comments? - .*? on .*?: \"/s, "")
    .replace(/\"\.\s*$/s, "")
    .trim();
}

for (const post of content.blog.posts) {
  const entry = copy[post.id];
  if (!entry) continue;
  const [slug, titleUa, titleEn, captionEn] = entry;
  post.slug = slug;
  post.title = { ua: titleUa, en: titleEn };
  post.caption = { ua: cleanCaption(post.caption.ua), en: captionEn };
  post.location = { ua: "Україна", en: "Ukraine" };
  post.tags = [...new Set([...post.caption.ua.matchAll(/#([\p{L}\p{N}_]+)/gu)].map((m) => m[1]))];
  for (const media of post.media) media.alt = titleEn;
}

