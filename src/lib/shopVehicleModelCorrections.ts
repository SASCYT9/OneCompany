function mergeModelCorrections(...sources: readonly ModelCorrections[]): ModelCorrections {
  const merged: Record<string, Record<string, readonly string[]>> = {};
  for (const source of sources) {
    for (const [make, corrections] of Object.entries(source)) {
      merged[make] = { ...merged[make], ...corrections };
    }
  }
  return merged;
}

