const SPACED_SLUG =
  /^(?:grand-|range-rover|discovery-sport|santa-fe|grande-punto|124-spider|c[345]-(?:aircross|picasso|spacetourer)|xsara-picasso|pajero-sport|space-star|almera-tino|tigra-twintop|zafira-life|panamera-sport-turismo|vel-satis|corolla-verso|land-cruiser|urban-cruiser|yaris-verso|golf-(?:plus|sportsvan)|gl[ce]-coupe)/i;

/** Cosmetic formatting only: punctuation and case never broaden model identity. */
export function formatVehicleModelLabel(value: string) {
  const cleaned = SPACED_SLUG.test(value) ? value.replace(/-/g, " ") : value;
  return cleaned
    .trim()
    .replace(/\s+/g, " ")
    .split(/([\s/-]+)/)
    .map((token) => {
      if (!/[a-z]/i.test(token)) return token;
      const lower = token.toLowerCase();
      if (WORD_CASE[lower]) return WORD_CASE[lower];
      if (/^id\./.test(lower)) return token.toUpperCase();
      if (/^(?:i\d+|ix\d+)$/.test(lower)) return lower;
      if (lower === "iv" && value.toLowerCase().includes("enyaq")) return "iV";
      if (UPPER_TOKENS.has(lower) || /^(?:[a-z]{1,3}\d+[a-z]*|\d+[a-z]{1,3}\d*)$/i.test(token))
        return token.toUpperCase();
      return lower[0]!.toUpperCase() + lower.slice(1);
    })
    .join("");
}
